export type Lang = 'tr' | 'en' | 'de' | 'es' | 'fr' | 'it' | 'pt' | 'ru' | 'ja' | 'ko' | 'zh' | 'ar';

export function deviceLang(): Lang {
  try {
    const code = getLocales()[0]?.languageCode?.toLowerCase();
    if (code && code in STRINGS) {
      return code as Lang;
    }
    return 'en';
  } catch {
    return 'en';
  }
}

export const STRINGS: Record<Lang, Strings> = {
  tr,
  en,
  de,
  es,
  fr,
  it,
  pt,
  ru,
  ja,
  ko,
  zh,
  ar,
};
